-- Create a profile automatically when a user signs up.
create or replace function public.handle_new_mathhub_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name'
  )
  on conflict (id) do update
  set full_name = excluded.full_name;

  return new;
end;
$$;

drop trigger if exists on_mathhub_user_created on auth.users;

create trigger on_mathhub_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_mathhub_user();
